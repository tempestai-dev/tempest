import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
import * as esbuild from 'esbuild';

const require = createRequire(import.meta.url);
const scriptDir = import.meta.dirname;
const mobileRoot = path.resolve(scriptDir, '..');
const outputPath = path.join(mobileRoot, 'lib', 'terminal-webview-engine.generated.js');
const target = 'chrome74';

const packages = ['@xterm/xterm', '@xterm/addon-fit', '@xterm/addon-webgl', '@xterm/addon-unicode11'];

async function readPackageVersion(pkg) {
  const p = require.resolve(`${pkg}/package.json`);
  const j = JSON.parse(await readFile(p, 'utf8'));
  return `${pkg}@${j.version}`;
}

function htmlSafe(value, tag) {
  return value.replace(new RegExp(`</${tag}`, 'gi'), `<\\/${tag}`);
}

async function buildEngineJs() {
  const result = await esbuild.build({
    stdin: {
      contents: `
        import { Terminal } from '@xterm/xterm'
        import { FitAddon } from '@xterm/addon-fit'
        import { Unicode11Addon } from '@xterm/addon-unicode11'
        import { WebglAddon } from '@xterm/addon-webgl'

        // Guards so a chrome74-syntax bundle still boots on older WebViews.
        if (typeof window.WeakRef === 'undefined') {
          window.WeakRef = function WeakRefShim(t) { this.__t = t }
          window.WeakRef.prototype.deref = function () { return this.__t }
        }
        if (typeof window.structuredClone === 'undefined') {
          window.structuredClone = function (v) { return JSON.parse(JSON.stringify(v)) }
        }
        if (typeof Element !== 'undefined' && !Element.prototype.replaceChildren) {
          Element.prototype.replaceChildren = function () {
            while (this.firstChild) this.removeChild(this.firstChild)
            this.append.apply(this, arguments)
          }
        }

        window.Terminal = Terminal
        window.FitAddon = { FitAddon }
        window.Unicode11Addon = { Unicode11Addon }
        window.WebglAddon = { WebglAddon }
      `,
      resolveDir: mobileRoot,
      sourcefile: 'terminal-webview-engine-entry.js',
    },
    bundle: true,
    format: 'iife',
    minify: true,
    platform: 'browser',
    target,
    legalComments: 'none',
    write: false,
    logLevel: 'silent',
  });
  return result.outputFiles[0].text;
}

async function main() {
  const [engineJs, rawCss, ...versions] = await Promise.all([
    buildEngineJs(),
    readFile(require.resolve('@xterm/xterm/css/xterm.css'), 'utf8'),
    ...packages.map(readPackageVersion),
  ]);

  // Strip comments; percent-encode any http(s):// xmlns URIs so a future
  // no-external-URL gate has nothing to catch.
  const engineCss = rawCss
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/http:\/\/www\.w3\.org\/2000\/svg/g, 'http%3A//www.w3.org/2000/svg');

  const source = [
    '// Generated by scripts/build-terminal-webview-engine.mjs.',
    `// Packages: ${versions.join(', ')}.`,
    `// Target: ${target}. Do not edit by hand; regenerate via npm postinstall.`,
    `export const XTERM_ENGINE_JS = ${JSON.stringify(htmlSafe(engineJs, 'script'))};`,
    `export const XTERM_ENGINE_CSS = ${JSON.stringify(htmlSafe(engineCss, 'style'))};`,
    '',
  ].join('\n');

  await writeFile(outputPath, source);
}

await main();
